import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { Client } from '../client/index.js';

if (!process.env.API_TOKEN) throw new Error('Set API_TOKEN before running the example');
const client = new Client({
  baseUrl: process.env.API_URL ?? 'http://127.0.0.1:4330',
  token: process.env.API_TOKEN,
});
const suffix = randomUUID().slice(0, 8);


const service = await client.createService({
  name: 'Example checkout ' + suffix,
  tier: 'critical',
  targetBps: 9990,
});
const subscriber = await client.createSubscriber({
  name: 'Example operations inbox',
  serviceIds: [service.id],
});
const monitor = await client.createMonitor({
  serviceId: service.id,
  name: 'Example heartbeat',
  failureThreshold: 2,
  recoveryThreshold: 2,
  intervalMs: 60_000,
});
await client.submitSample(monitor.id, { ok: false, message: 'First failing observation' });
const failure = await client.submitSample(monitor.id, {
  ok: false,
  message: 'Second failing observation',
}, { idempotencyKey: suffix + ':failure-2' });
const issueId = failure.monitor.activeIncidentId;
assert.ok(issueId);
let issue = await client.getIncident(issueId);
issue = await client.assignIncident(issueId, { owner: 'example-oncall', revision: issue.revision });
issue = await client.transitionIncident(issueId, {
  status: 'investigating',
  message: 'Inspecting dependency timeout',
  revision: issue.revision,
});
await client.addIncidentNote(issueId, { message: 'Dependency recovered after restart' });
await client.submitSample(monitor.id, { ok: true });
await client.submitSample(monitor.id, { ok: true });
issue = await client.getIncident(issueId);
assert.equal(issue.status, 'resolved');
await client.createPostmortem(issueId, {
  summary: 'Example checkout requests failed during a dependency timeout.',
  rootCause: 'Deliberate failures generated by this demonstration.',
  prevention: ['Keep example monitors separate from real operational checks.'],
});
const notifications = await client.listNotifications();
const relevant = notifications.items.filter(item => item.subscriberId === subscriber.id);
assert.ok(relevant.length >= 2);
assert.ok(relevant.every(item => item.status === 'pending'));
const latestMonitor = (await client.listMonitors()).items.find(item => item.id === monitor.id);
await client.controlMonitor(monitor.id, { enabled: false, revision: latestMonitor.revision });
console.log(JSON.stringify({ incidentId: issueId, notifications: relevant.length }, null, 2));
console.log('Incident resolved; example monitor disabled. Notifications remain in the outbox.');
